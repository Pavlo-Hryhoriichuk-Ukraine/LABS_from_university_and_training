class HuffmanFFTSpectralAnalyzer:
    """
    Analyzes the binary Huffman sequence using Real Fast Fourier Transform (RFFT)
    to detect structural periodicity and assess text generation origin.
    """

    def __init__(self, binary_sequence: str) -> None:
        self.raw_sequence = binary_sequence
        self.signal: np.ndarray | None = None
        self.frequencies: np.ndarray | None = None
        self.amplitudes: np.ndarray | None = None
        self.peaks_indices: np.ndarray | None = None

    def _map_to_signal(self) -> None:
        """
        Converts the binary string into a highly optimized NumPy array.
        Maps '0' -> -1.0 and '1' -> 1.0 (float32) for FFT processing.
        """
        # Encode string to bytes to utilize zero-copy buffer mapping
        byte_buffer = self.raw_sequence.encode('ascii')
        raw_array = np.frombuffer(byte_buffer, dtype=np.uint8)

        # Vectorized mathematical transformation: (val - 48) * 2 - 1
        self.signal = (raw_array.astype(np.float32) - 48.0) * 2.0 - 1.0

    def _apply_fft(self) -> None:
        """
        Applies Real Fast Fourier Transform (RFFT) to the binary signal.
        Extracts frequency bins and computes normalized amplitudes.
        """
        if self.signal is None:
            raise ValueError("Signal is not initialized. Call _map_to_signal() first.")

        n = len(self.signal)

        # Wrap in np.asarray() to resolve Pylance type-hinting artifacts
        fft_result = np.asarray(rfft(self.signal))
        self.frequencies = rfftfreq(n, d=1.0)
        raw_amplitudes = np.abs(fft_result)

        # Energy scaling normalization
        normalized_amps = (raw_amplitudes * 2.0) / n

        # DC component and Nyquist do not have negative counterparts
        normalized_amps[0] /= 2.0
        if n % 2 == 0:
            normalized_amps[-1] /= 2.0

        self.amplitudes = normalized_amps

    def _analyze_peaks(self) -> dict:
        """
        Detects significant resonance peaks in the amplitude spectrum to
        differentiate between structural noise and generated patterns.

        Returns:
            dict: Metrics including peak count, max amplitude, and SNR.
        """
        if self.amplitudes is None:
            raise ValueError("Amplitudes are not computed. Call _apply_fft() first.")

        # Robust noise baseline using median
        baseline_noise = float(np.median(self.amplitudes))

        # Dynamic thresholds
        min_height = baseline_noise * 3.0
        min_prominence = baseline_noise * 1.5

        # Find peaks
        peaks_indices, properties = find_peaks(
            self.amplitudes,
            height=min_height,
            prominence=min_prominence
        )

        peak_count = int(len(peaks_indices))

        self.peaks_indices = peaks_indices

        if peak_count > 0 and "peak_heights" in properties:
            max_amplitude = float(np.max(properties["peak_heights"]))
            snr = float(max_amplitude / (baseline_noise + 1e-10))
        else:
            max_amplitude = float(np.max(self.amplitudes)) if len(self.amplitudes) > 0 else 0.0
            snr = 1.0

        metrics = {
            "peak_count": peak_count,
            "max_amplitude": max_amplitude,
            "baseline_noise": baseline_noise,
            "signal_to_noise_ratio": snr,
        }

        return metrics

    def evaluate_origin(self, metrics: dict) -> str:
        """
        Evaluates spectral metrics to classify the text origin.

        Args:
            metrics (dict): The dictionary returned by _analyze_peaks().

        Returns:
            str: "Human" if the spectrum is chaotic, "AI" if highly structured.
        """
        peaks = metrics.get("peak_count", 0)
        snr = metrics.get("signal_to_noise_ratio", 1.0)

        # Heuristic rules for classification
        # Adjust these thresholds based on empirical testing with real texts.
        if peaks >= 50 and snr >= 4.0:
            return "Human poetry"
        elif peaks > 15 and snr >= 3.5:
            return "Generated by AI"
        else:
            return "Human classic texts"

    def run_pipeline(self) -> dict:
        """
        Executes the entire spectral analysis pipeline.

        Returns:
            dict: The final report containing metrics and the verdict.
        """
        self._map_to_signal()
        self._apply_fft()
        metrics = self._analyze_peaks()
        metrics["verdict"] = self.evaluate_origin(metrics)

        return metrics



class SpectralVisualizer:
    """
    Handles the visualization of spectral data, separating rendering logic
    from mathematical analysis (adhering to SRP).
    """

    def __init__(self, analyzer: HuffmanFFTSpectralAnalyzer) -> None:
        self.analyzer = analyzer

    def plot_spectrum(self, filename: str, show_peaks: bool = True) -> None:
        """
        Plots the frequency spectrum using matplotlib.
        Optionally highlights the detected structural peaks.
        """
        # Defensive programming: ensure data is available
        if self.analyzer.frequencies is None or self.analyzer.amplitudes is None:
            raise ValueError("No spectral data to plot. Run the pipeline first.")

        freqs = self.analyzer.frequencies
        amps = self.analyzer.amplitudes

        # Initialize a modern, large plot figure
        plt.figure(figsize=(12, 6))

        plt.plot(
            freqs,
            amps,
            color="steelblue",
            linewidth=1.0,
            alpha=0.7,
            label="Full Spectrum"
        )

        # Step 2: Highlight the peaks
        if show_peaks and self.analyzer.peaks_indices is not None and len(self.analyzer.peaks_indices) > 0:
            peak_idx = self.analyzer.peaks_indices
            plt.scatter(
                freqs[peak_idx],
                amps[peak_idx],
                color="crimson",
                marker="X",  # 'X' marks the spot clearly
                s=50,        # Size of the marker
                zorder=5,    # Ensure dots are drawn ON TOP of the blue line
                label=f"Detected Peaks ({len(peak_idx)})"
            )


        plt.title(f"Plot of the peaks of the Fast Discrete Fourier Transform for: '{filename}'", fontsize=14)
        plt.xlabel("Frequency (cycles per bit)", fontsize=12)
        plt.ylabel("Normalized Amplitude", fontsize=12)

        plt.grid(True, linestyle='--', alpha=0.6)
        plt.legend()

        plt.tight_layout()
        plt.show()



