class WordHuffmanFFTSpectralAnalyzer:
    """
    Аналізує бінарний потік послівного Гаффмана за допомогою RFFT
    для виявлення спектральних піків і структурної періодичності.
    """

    def __init__(self, binary_sequence: str) -> None:
        self.raw_sequence = binary_sequence
        self.signal: np.ndarray | None = None
        self.frequencies: np.ndarray | None = None
        self.amplitudes: np.ndarray | None = None
        self.peaks_indices: np.ndarray | None = None

    def _map_to_signal(self) -> None:
        """
        Перетворює бінарний рядок послівного Гаффмана на сигнал:
        '0' -> -1.0, '1' -> 1.0 (float32).
        """
        byte_buffer = self.raw_sequence.encode("ascii")
        raw_array = np.frombuffer(byte_buffer, dtype=np.uint8)
        self.signal = (raw_array.astype(np.float32) - 48.0) * 2.0 - 1.0

    def _apply_fft(self) -> None:
        """
        Застосовує дійсне швидке перетворення Фур'є (RFFT) до сигналу
        та обчислює нормовані амплітуди.
        """
        if self.signal is None:
            raise ValueError(
                "Сигнал не ініціалізовано. Спочатку викличте _map_to_signal()."
            )

        n = len(self.signal)
        fft_result = np.asarray(rfft(self.signal))
        self.frequencies = rfftfreq(n, d=1.0)
        raw_amplitudes = np.abs(fft_result)

        normalized_amps = (raw_amplitudes * 2.0) / n
        normalized_amps[0] /= 2.0
        if n % 2 == 0:
            normalized_amps[-1] /= 2.0

        self.amplitudes = normalized_amps

    def _analyze_peaks(self) -> dict:
        """
        Шукає резонансні піки спектра для послівного потоку токенів.
        """
        if self.amplitudes is None:
            raise ValueError("Амплітуди не обчислені. Спочатку викличте _apply_fft().")

        baseline_noise = float(np.median(self.amplitudes))

        min_height = baseline_noise * 3.0
        min_prominence = baseline_noise * 1.5

        peaks_indices, properties = find_peaks(
            self.amplitudes, height=min_height, prominence=min_prominence
        )

        peak_count = len(peaks_indices)
        self.peaks_indices = peaks_indices

        if peak_count > 0 and "peak_heights" in properties:
            max_amplitude = float(np.max(properties["peak_heights"]))
            snr = float(max_amplitude / (baseline_noise + 1e-10))
        else:
            max_amplitude = (
                float(np.max(self.amplitudes)) if len(self.amplitudes) > 0 else 0.0
            )
            snr = 1.0

        return {
            "peak_count": peak_count,
            "max_amplitude": max_amplitude,
            "baseline_noise": baseline_noise,
            "signal_to_noise_ratio": snr,
        }

    def evaluate_origin(self, metrics: dict) -> str:
        peaks = metrics.get("peak_count", 0)
        snr = metrics.get("signal_to_noise_ratio", 1.0)

        if peaks >= 50 and snr >= 4.0:
            return "Human poetry / High rhythm"
        elif peaks > 15 and snr >= 3.5:
            return "Generated by AI"
        else:
            return "Human prose / Classic texts"

    def run_pipeline(self) -> dict:
        self._map_to_signal()
        self._apply_fft()
        metrics = self._analyze_peaks()
        metrics["verdict"] = self.evaluate_origin(metrics)
        return metrics


class SpectralVisualizer:
    """
    Візуалізація спектра частот та резонансних піків послівного Гаффмана.
    """

    def __init__(self, analyzer: WordHuffmanFFTSpectralAnalyzer) -> None:
        self.analyzer = analyzer

    def plot_spectrum(self, base_name: str, show_peaks: bool = True) -> None:
        if self.analyzer.frequencies is None or self.analyzer.amplitudes is None:
            raise ValueError(
                "Немає даних для побудови графіка. Спочатку запустіть run_pipeline()."
            )

        freqs = self.analyzer.frequencies
        amps = self.analyzer.amplitudes

        plt.figure(figsize=(12, 6))
        plt.plot(
            freqs,
            amps,
            color="steelblue",
            linewidth=1.0,
            alpha=0.75,
            label="Word-Huffman Spectrum",
        )

        if (
            show_peaks
            and self.analyzer.peaks_indices is not None
            and len(self.analyzer.peaks_indices) > 0
        ):
            peak_idx = self.analyzer.peaks_indices
            plt.scatter(
                freqs[peak_idx],
                amps[peak_idx],
                color="crimson",
                marker="X",
                s=55,
                zorder=5,
                label=f"Detected Peaks ({len(peak_idx)})",
            )

        plt.title(
            f"Word-Level Huffman FFT Spectrum for: '{base_name}'",
            fontsize=13,
            pad=12,
        )
        plt.xlabel("Frequency (cycles per bit)", fontsize=11)
        plt.ylabel("Normalized Amplitude", fontsize=11)
        plt.grid(True, linestyle="--", alpha=0.5)
        plt.legend()
        plt.tight_layout()

        # Назва файлу: спочатку назва тексту, потім суфікс
        plot_output_path = SAVE_DIR / f"{base_name}_FFT_WordHuffman_spectrum.png"
        plt.savefig(plot_output_path, dpi=300)
        print(f"📊 Графік спектра успішно збережено: {plot_output_path.resolve()}")

        plt.show()


def run_word_huffman_fft(filename: str):
    base_name = filename.removesuffix(".txt")
    file_target = f"{base_name}.txt"

    file_path = ROOT / "Science_code" / "text_algorithms" / "texts" / file_target

    if not file_path.is_file():
        raise FileNotFoundError(f"Файл не знайдено за шляхом: {file_path.resolve()}")

    print(f"📖 Читання файлу: {file_path.resolve()}")
    with open(file_path, "r", encoding="utf-8") as f:
        text = f.read()

    if not text.strip():
        raise ValueError("Файл порожній!")

    # 1. Послівна токенізація
    tokens = tokenize_text(text)
    total_tokens = len(tokens)

    # 2. Побудова дерева Гаффмана для слів
    root, frequencies = build_huffman_tree(tokens)
    huffman_codes = huffman_code_tree(root)

    # 3. Лексичні метрики (H, L, R)
    H, L, R = analyze_word_huffman_metrics(total_tokens, frequencies, huffman_codes)  # type: ignore

    # 4. Кодування послівного потоку в єдиний бінарний рядок
    binary_sequence = "".join(huffman_codes[token] for token in tokens)

    # 5. Спектральний аналіз Фур'є (RFFT)
    analyzer = WordHuffmanFFTSpectralAnalyzer(binary_sequence)
    report = analyzer.run_pipeline()

    # 6. Збереження звіту: спочатку назва тексту, потім суфікс
    report_output_path = SAVE_DIR / f"{base_name}_FFT_WordHuffman_report.txt"
    with open(report_output_path, "w", encoding="utf-8") as rep_file:
        rep_file.write("=" * 60 + "\n")
        rep_file.write(f" 🔍 Звіт аналізу (Word-Level Huffman + FFT): {base_name}\n")
        rep_file.write("=" * 60 + "\n")
        rep_file.write(f"Загальна кількість токенів (слів + знаків) : {total_tokens}\n")
        rep_file.write(
            f"Унікальних токенів (розмір словника)      : {len(frequencies)}\n"
        )
        rep_file.write(
            f"Довжина бінарного потоку Гаффмана         : {len(binary_sequence)} біт\n"
        )
        rep_file.write("-" * 60 + "\n")
        rep_file.write(
            f"Ентропія Шеннона (H)                      : {H:.5f} біт/слово\n"
        )
        rep_file.write(
            f"Середня довжина коду (L)                  : {L:.5f} біт/слово\n"
        )
        rep_file.write(
            f"Надлишковість (R = L - H)                 : {R:.5f} біт/слово\n"
        )
        rep_file.write("-" * 60 + "\n")
        rep_file.write(
            f"Кількість резонансних піків (Peak Count)  : {report['peak_count']}\n"
        )
        rep_file.write(
            f"Базовий рівень шуму (Baseline Noise)      : {report['baseline_noise']:.6f}\n"
        )
        rep_file.write(
            f"Максимальна амплітуда піку                : {report['max_amplitude']:.6f}\n"
        )
        rep_file.write(
            f"Співвідношення сигнал/шум (SNR)           : {report['signal_to_noise_ratio']:.2f}\n"
        )
        rep_file.write("-" * 60 + "\n")
        rep_file.write(
            f"Вердикт класифікатора                     : {report['verdict']}\n"
        )
        rep_file.write("=" * 60 + "\n")

    print(f"📝 Текстовий звіт збережено: {report_output_path.resolve()}")

    # 7. Вивід у консоль
    print("\n" + "=" * 55)
    print(f" 🔍 Звіт аналізу (Word-Level Huffman + FFT) для: {base_name}")
    print("=" * 55)
    print(f"Ентропія Шеннона (H)       : {H:.5f} біт/слово")
    print(f"Середня довжина коду (L)   : {L:.5f} біт/слово")
    print(f"Надлишковість (R = L - H)  : {R:.5f} біт/слово")
    print("-" * 55)
    print(f"Кількість піків (Peak Count): {report['peak_count']}")
    print(f"Рівень шуму (Noise Level)  : {report['baseline_noise']:.6f}")
    print(f"Макс. амплітуда піку       : {report['max_amplitude']:.6f}")
    print(f"Співвідношення сигнал/шум  : {report['signal_to_noise_ratio']:.2f}")
    print("-" * 55)
    print(f"Вердикт класифікатора      : {report['verdict']}")
    print("=" * 55 + "\n")

    # 8. Побудова та збереження зображення графіка
    SpectralVisualizer(analyzer).plot_spectrum(base_name)


